def generate_code(context: UIBuilderContext) -> UIBuilderContext:
    """
    Stage 6: Generate production-ready React code.
    
    Generates:
    - Component .tsx/.jsx file
    - CSS Module stylesheet (if applicable)
    - Index barrel export
    
    Args:
        context: UIBuilderContext with layout and components defined
    
    Returns:
        Updated context with generated_files populated
    """
    context.current_stage = 6
    
    # Validate prerequisites
    if not context.component_name:
        context.mark_failed("Component name not set. Stage 5 must complete first.")
        return context
    
    if not context.component_mappings:
        context.mark_failed("No component mappings. Stage 4 must complete first.")
        return context
    
    comp_name = context.component_name
    file_ext = "tsx" if context.uses_typescript else "jsx"
    comp_dir = context.component_dir or "src/components"
    
    # Generate component code
    component_code = generate_component_code(context)
    context.generated_files.append(GeneratedFile(
        path=f"{comp_dir}/{comp_name}/{comp_name}.{file_ext}",
        content=component_code,
        type="component",
        language="typescript" if context.uses_typescript else "javascript"
    ))
    
    # Generate CSS if using CSS Modules
    if context.css_strategy == "css-modules":
        css_code = generate_css_module(context)
        context.generated_files.append(GeneratedFile(
            path=f"{comp_dir}/{comp_name}/{comp_name}.module.css",
            content=css_code,
            type="stylesheet",
            language="css"
        ))
    
    # Generate index file
    index_code = generate_index_file(context)
    context.generated_files.append(GeneratedFile(
        path=f"{comp_dir}/{comp_name}/index.ts",
        content=index_code,
        type="index",
        language="typescript"
    ))
    
    return context


