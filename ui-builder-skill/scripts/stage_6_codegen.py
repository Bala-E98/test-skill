def generate_index_file(context: UIBuilderContext) -> str:
    """
    Generate index.ts barrel export.
    
    Returns:
        Index file code
    """
    comp_name = context.component_name
    file_ext = "tsx" if context.uses_typescript else "jsx"
    
    return f"""export {{ {comp_name}, default }} from './{comp_name}.{file_ext}';
export type {{ {comp_name}Props }} from './{comp_name}.{file_ext}';
"""


