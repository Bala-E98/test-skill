def generate_component_code(context: UIBuilderContext) -> str:
    """
    Generate React component code.
    
    Returns:
        Complete .tsx/.jsx component code
    """
    comp_name = context.component_name
    is_ts = context.uses_typescript
    file_ext = "tsx" if is_ts else "jsx"
    
    # Build imports
    imports = ["import React, { useState } from 'react';"]
    
    # Add Syncfusion imports
    imported_components = set()
    for mapping in context.component_mappings:
        if mapping.package and mapping.component not in imported_components:
            imports.append(f"import {{ {mapping.component} }} from '{mapping.package}';")
            imported_components.add(mapping.component)
    
    # Add styles import
    if context.css_strategy == "css-modules":
        imports.append(f"import styles from './{comp_name}.module.css';")
    
    imports_str = "\n".join(imports)
    
    # Build props interface (TypeScript only)
    props_interface = ""
    if is_ts:
        props_interface = f"""
interface {comp_name}Props {{
  onSubmit?: (data: any) => void;
  className?: string;
}}
"""
    
    # Build state declarations
    state_vars = []
    for field in context.layout_fields:
        if field.type in ["text", "password", "email", "textarea"]:
            state_vars.append(f"  const [{ field.id}, set{field.id.title()}] = useState('');")
        elif field.type == "checkbox":
            state_vars.append(f"  const [{field.id}, set{field.id.title()}] = useState(false);")
    
    state_str = "\n".join(state_vars)
    
    # Build JSX for fields
    jsx_fields = []
    for field in context.layout_fields:
        mapping = next((m for m in context.component_mappings if m.field_id == field.id), None)
        
        if field.type in ["text", "password", "email"]:
            jsx_fields.append(f"""
        <div className={{styles.fieldGroup}}>
          <label htmlFor="{field.id}">
            {field.label}
            {' ' + '<span className={styles.required}>*</span>' if field.required else ''}
          </label>
          <{mapping.component}
            id="{field.id}"
            type="{field.type}"
            value={{{field.id}}}
            change={{(e: any) => set{field.id.title()}(e.value)}}
            placeholder="{field.placeholder or 'Enter ' + field.label.lower()}"
            {'required={true}' if field.required else ''}
          />
        </div>""")
        
        elif field.type == "textarea":
            jsx_fields.append(f"""
        <div className={{styles.fieldGroup}}>
          <label htmlFor="{field.id}">{field.label}</label>
          <{mapping.component}
            id="{field.id}"
            multiline={{true}}
            value={{{field.id}}}
            change={{(e: any) => set{field.id.title()}(e.value)}}
            placeholder="{field.placeholder or field.label}"
          />
        </div>""")
        
        elif field.type == "checkbox":
            jsx_fields.append(f"""
        <{mapping.component}
          id="{field.id}"
          label="{field.label}"
          checked={{{field.id}}}
          change={{(e: any) => set{field.id.title()}(e.checked)}}
        />""")
        
        elif field.type == "button":
            jsx_fields.append(f"""
        <{mapping.component}
          type="submit"
          isPrimary={{true}}
          className={{styles.submitButton}}
        >
          {field.label}
        </{mapping.component}>""")
        
        elif field.type == "link":
            jsx_fields.append(f"""
        <a href="#" className={{styles.link}}>{field.label}</a>""")
        
        elif field.type == "divider":
            jsx_fields.append(f"""
        <div className={{styles.divider}}>
          <span>{field.label}</span>
        </div>""")
    
    jsx_fields_str = "\n".join(jsx_fields)
    
    # Build complete component
    component_code = f"""/**
 * {comp_name} Component
 * 
 * Generated by UI Builder Skill
 * Variant: {context.selected_variant}
 * WCAG 2.1 AA Compliant | Responsive Design | Production Ready
 * 
 * @component
 */

{imports_str}
{props_interface}

export const {comp_name}{': React.FC<' + comp_name + 'Props>' if is_ts else ''} = ({{ onSubmit, className }}) => {{
{state_str}

  const handleSubmit = (e{': React.FormEvent' if is_ts else ''}) => {{
    e.preventDefault();
    
    if (onSubmit) {{
      const data = {{
{chr(10).join([f'        {field.id},' for field in context.layout_fields if field.type not in ['button', 'link', 'divider']])}
      }};
      onSubmit(data);
    }}
  }};

  return (
    <form 
      className={{`${{styles.container}} ${{className || ''}}`}}
      onSubmit={{handleSubmit}}
      aria-label="{context.layout_metadata.get('variant_name', comp_name)}"
    >
      <h1 className={{styles.title}}>
        {context.layout_metadata.get('variant_name', 'Form')}
      </h1>
      
{jsx_fields_str}
    </form>
  );
}};

export default {comp_name};
"""
    
    return component_code


